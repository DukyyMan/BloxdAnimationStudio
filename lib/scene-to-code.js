// ── Generate Code From Scene ─────────────────────────────────────────────────
// Deterministic, fully local reverse of the AI Prompt Builder: turn the real
// scene data into a script for the Code Editor's scripting API (see
// CODE-EDITOR.md). No AI, no network, no timestamps — the same scene always
// produces byte-identical code. Only commands that actually exist in the
// scripting API are emitted; everything the API cannot express is reported in
// `limitations` instead of being faked.

const SCRIPT_EASES=new Set(['linear','smooth','in','out','inout','step','bezier','spline']);
// Internal rig joint (lib/character.js JOINTS keys) → scripting API part name.
const JOINT_TO_API={head:'head',body:'body',armL:'leftArm',armR:'rightArm',forearmL:'leftElbow',forearmR:'rightElbow',legL:'leftLeg',legR:'rightLeg',shinL:'leftKnee',shinR:'rightKnee'};
const PRESET_TO_LIGHT={'golden':'golden hour','day':'daylight','night':'night','studio':'studio','sunrise':'sunrise','sunset':'sunset','moonlight':'moonlight','cinematic':'cinematic'};
const MAX_SCRIPT_DURATION=60,MAX_KEYS_PER_COMMAND=120;

const r6=n=>Math.round(n*1e6)/1e6;
const vec3=(a,fx=n=>r6(n))=>Array.isArray(a)?`{ x: ${fx(a[0])}, y: ${fx(a[1])}, z: ${fx(a[2])} }`:'{ x: 0, y: 0, z: 0 }';
const deg=rad=>r6(rad*180/Math.PI);
const q=(v)=>typeof v==='string'?'"'+v.replace(/\\/g,'\\\\').replace(/"/g,'\\"')+'"':String(v);

function slug(name,fallback){
  let s=String(name||'').toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-+|-+$/g,'').slice(0,40);
  return /^[a-z]/.test(s)?s:fallback;
}

// Merge equal blocks into inclusive runs along X, then merge rows that share
// the same extent and type across consecutive Z — large flat layers collapse
// into a handful of terrain.fill commands, keeping big scenes well inside the
// scripting command budget.
// World cells arrive as ['x,y,z', blockId] entries from the scene snapshot.
function terrainRuns(cells){
  const norm=cells.map(c=>Array.isArray(c)&&typeof c[0]==='string'
    ?[...c[0].split(',').map(Number),c[1]]
    :c).filter(c=>c.length===4&&c.slice(0,3).every(n=>Number.isFinite(n)));
  const rows=new Map(); // 'y,z' -> runs along x
  for(const [x,y,z,type] of norm){
    if(x<-50||x>50||y<-50||y>50||z<-50||z>50)continue;
    const key=y+','+z;
    if(!rows.has(key))rows.set(key,[]);
    rows.get(key).push([x,type]);
  }
  const lineRuns=[];
  for(const [key,row] of [...rows.entries()].sort((a,b)=>a[0].localeCompare(b[0],'en',{numeric:true}))){
    const [y,z]=key.split(',').map(Number);
    row.sort((a,b)=>a[0]-b[0]);
    let run=null;
    for(const [x,type] of row){
      if(run&&run.type===type&&x===run.x1+1)run.x1=x;
      else{if(run)lineRuns.push({y,z,...run});run={x0:x,x1:x,type};}
    }
    if(run)lineRuns.push({y,z,...run});
  }
  // Merge rows with identical extent/type across consecutive Z at the same Y.
  const byY=new Map();
  for(const run of lineRuns){if(!byY.has(run.y))byY.set(run.y,[]);byY.get(run.y).push(run);}
  const merged=[];
  for(const [y,list] of [...byY.entries()].sort((a,b)=>a[0]-b[0])){
    list.sort((a,b)=>a.z-b.z||a.x0-b.x0);
    let cur=null;
    for(const run of list){
      if(cur&&cur.type===run.type&&cur.x0===run.x0&&cur.x1===run.x1&&run.z===cur.z1+1)cur.z1=run.z;
      else{if(cur)merged.push(cur);cur={...run,z1:run.z};}
    }
    if(cur)merged.push(cur);
  }
  return merged;
}

export function generateSceneCode({snapshot,catalog,cameraKeys=[],cameraSmooth=true,sunKeys=[],timelineState,editorVersion=''}){
  const limits=new Set();
  const note=m=>limits.add(m);
  const stats={terrainCells:0,terrainRuns:0,characters:0,blocks:0,items:0,meshes:0,skipped:0,poseKeys:0,objectKeys:0,cameraKeys:0,sunKeys:0};
  const L=[]; // generated lines
  const used=new Set();
  const idFor=r=>{
    if(r.options?.scriptId&&/^[A-Za-z][A-Za-z0-9_-]{0,47}$/.test(r.options.scriptId))return r.options.scriptId;
    let base=slug(r.name,'obj')||'obj',cand=base,n=2;
    while(used.has(cand))cand=base+'-'+(n++);
    used.add(cand);return cand;
  };
  L.push('// Generated by Bloxd Animation Studio'+(editorVersion?' '+editorVersion:'')+' — "Generate Code From Scene".');
  L.push('// Source scene: '+q(snapshot.sceneName||'Untitled')+'.');
  L.push('// Deterministic output: the same scene produces the same script (no timestamps).');
  L.push('// Runs entirely in the local Code Editor — validate, then run to rebuild the scene.');
  L.push('');
  L.push('async function main(api) {');
  L.push('  const { project, scene, timeline, camera, lights, terrain, mesh } = api;');
  L.push('');

  // ── Project & timeline ──
  L.push('  // ── Timeline ─────────────────────────────────────────────────');
  L.push('  project.setGeneratedMode("replace"); // rebuild generated content, keep manually edited non-generated objects');
  const duration=Math.min(MAX_SCRIPT_DURATION,Math.max(2,Math.round((timelineState?.duration??8)*100)/100));
  if((timelineState?.duration??8)>MAX_SCRIPT_DURATION)note(`The clip duration (${timelineState.duration}s) exceeds the scripting maximum of ${MAX_SCRIPT_DURATION}s; the script uses ${MAX_SCRIPT_DURATION}s. Extend timeline.setDuration after running if needed.`);
  L.push(`  timeline.setDuration(${duration});`);
  const fps=Math.max(1,Math.min(120,Math.round(timelineState?.fps??24)));
  L.push(`  timeline.setFPS(${fps});`);
  if(timelineState?.loop)note('Timeline looping is an editor playback setting; the scripting API cannot set it. Re-enable Loop after running.');
  L.push('');

  // ── Terrain ──
  const cells=[...(snapshot.world?.blocks||[])];
  if(cells.length){
    L.push('  // ── Terrain ──────────────────────────────────────────────────');
    L.push('  terrain.clear(); // replaces the whole terrain grid with the cells below');
    const runs=terrainRuns(cells);
    stats.terrainRuns=runs.length;stats.terrainCells=cells.length;
    const skippedCells=cells.length-stats.terrainCells;
    if(skippedCells>0)note(skippedCells+' terrain cells fall outside the scripting ±50 grid bounds and were skipped.');
    for(const run of runs){
      const block=run.type==='air'?'"air"':q(run.type);
      L.push(`  terrain.fill({ from: { x: ${run.x0}, y: ${run.y}, z: ${run.z} }, to: { x: ${run.x1}, y: ${run.y}, z: ${run.z} }, blockName: ${block} });`);
    }
    L.push('');
  }

  // ── Objects ──
  const objectLines=[];const animLines=[];
  for(const r of snapshot.objects||[]){
    const id=idFor(r);
    const t=r.transform||{position:[0,0,0],rotation:[0,0,0],scale:[1,1,1]};
    const common=`position: ${vec3(t.position)}`;
    const rot=`rotation: ${vec3(t.rotation,deg)}`;
    const scale=`scale: ${vec3(t.scale)}`;
    if(r.type==='character'){
      stats.characters++;
      const opts=[`id: ${q(id)}`,`name: ${q(r.name||id)}`,common];
      if(JSON.stringify(t.rotation)!=='[0,0,0]')opts.push(rot);
      if(JSON.stringify(t.scale)!=='[1,1,1]')opts.push(scale);
      const skin=r.options?.skin;if(skin&&skin!=='default')opts.push(`skin: ${q(skin)}`);
      if(r.options?.visibility===false)opts.push('visibility: false');
      objectLines.push(`  const ${id} = await scene.addCharacter({ ${opts.join(', ')} });`);
      if(r.options?.material)note(`Object "${r.name}" carries a custom material override; scene.setMaterial can re-apply color/roughness but skin tinting details may differ. Add it manually if needed.`);
      if(r.character?.detached&&Object.keys(r.character.detached).length)note(`"${r.name}" has detached body parts; the scripting API cannot detach joints. The character is created with its standard rig.`);
      if(r.character?.armor)note(`"${r.name}" wears armor; the scripting API cannot equip armor. Equip it in the inspector after running.`);
      if(r.character?.tool&&r.character.tool!=='none')note(`"${r.name}" holds "${r.character.tool}"; the scripting API cannot equip held items. Use the inspector's Held item selector after running.`);
      // Pose & motion keys.
      const keys=(r.character?.keys||[]).slice().sort((a,b)=>a.time-b.time);
      for(const k of keys){
        const ease=k.ease&&SCRIPT_EASES.has(k.ease)?`, { ease: ${q(k.ease)} }`:(k.ease?(()=>{note(`Key easing "${k.ease}" at ${k.time}s on "${r.name}" is not available to scripts (Hold is a timeline-only ease); the key uses smooth interpolation.`);return '';})():'');
        const wrapOut=(k,j)=>{const d=k.pose[j].map(deg);const wrapped=d.map(v=>Math.abs(v)>720?(((v+180)%360+360)%360-180):v);if(wrapped.some((v,i)=>v!==d[i]))note(`"${r.name}" has ${JOINT_TO_API[j]} rotations beyond the scripting API's ±720° joint range (e.g. multi-turn spins at ${k.time}s); they were wrapped to the equivalent angle. Full spins may render differently because scripts interpolate the shortest path — re-pose in the editor if the motion matters.`);return wrapped;};
        const parts=(k.pose&&typeof k.pose==='object')?Object.keys(JOINT_TO_API).filter(j=>Array.isArray(k.pose[j])&&k.pose[j].some(v=>v)).map(j=>`${JOINT_TO_API[j]}: { rotation: ${vec3(wrapOut(k,j))} }`):[];
        if(k.preset){note(`A motion-preset key at ${k.time}s on "${r.name}" is emitted as timeline.preset, which bakes a short motion instead of a single frozen pose.`);animLines.push(`  timeline.preset(${id}, ${q(String(k.preset)[0].toUpperCase()+String(k.preset).slice(1))}, { time: ${r6(k.time)}, duration: 0.5 });`);stats.poseKeys++;continue;}
        if(parts.length){
          animLines.push(`  timeline.keyPose(${id}, { time: ${r6(k.time)}, parts: { ${parts.join(', ')} } }${ease});`);
          stats.poseKeys++;
        }
        if(k.position||k.rotation||k.scale){
          const fields=[`time: ${r6(k.time)}`];
          if(k.position)fields.push(`position: ${vec3(k.position)}`);
          if(k.rotation)fields.push(`rotation: ${vec3(k.rotation,deg)}`);
          if(k.scale)fields.push(`scale: ${vec3(k.scale)}`);
          animLines.push(`  timeline.key(${id}, { ${fields.join(', ')} }${ease});`);
          stats.objectKeys++;
        }
        if(k.bodyLift!==undefined&&k.bodyLift)note(`"${r.name}" has body-lift keys; keyPose cannot set body lift. Re-apply body lift in the editor if needed.`);
        if(k.held)note(`"${r.name}" has held-item keys; the scripting API cannot key held items. Re-key them in the editor if needed.`);
        const pose=k.pose||{};
        if(pose.move&&Object.values(pose.move).some(v=>Array.isArray(v)&&v.some(n=>n)))note(`"${r.name}" has per-part move keys; keyPose supports part rotation only.`);
        if(pose.scale&&Object.values(pose.scale).some(v=>Array.isArray(v)&&v.some(n=>n!==1)))note(`"${r.name}" has per-part scale keys; keyPose supports part rotation only.`);
        if(pose.offset)note(`"${r.name}" has body-lift (offset) keys; keyPose cannot set body lift.`);
        if(!parts.length&&!k.position&&!k.rotation&&!k.scale&&!k.preset&&k.time>0)note(`A key at ${k.time}s on "${r.name}" holds no scripted channels and was skipped.`);
      }
      if(r.draft)note(`"${r.name}" has an unapplied pending edit; scripts reproduce saved keys only. Apply the pending edit in the editor first if you want it included.`);
    }
    else if(r.type==='tool'){
      stats.items++;
      const asset=r.options?.asset;if(!asset){stats.skipped++;note(`"${r.name}" is a tool without a recorded asset name and was skipped.`);continue;}
      objectLines.push(`  scene.addAsset(${q(asset)}, { id: ${q(id)}, name: ${q(r.name||id)}, ${common}, ${rot}, ${scale} });`);
      if(r.options?.material)objectLines.push(`  scene.setMaterial(scene.get(${q(id)}), { color: ${q(r.options.material.color||'#ffffff')} });`);
      emitObjectKeys(r,id,animLines,stats,note);
    }
    else if(r.type==='block'){
      stats.blocks++;
      const asset=r.options?.block;if(!asset){stats.skipped++;note(`"${r.name}" is a block without a recorded block id and was skipped.`);continue;}
      objectLines.push(`  scene.addAsset(${q(asset)}, { id: ${q(id)}, name: ${q(r.name||id)}, ${common}, ${rot}, ${scale} });`);
      if(r.options?.material)objectLines.push(`  scene.setMaterial(scene.get(${q(id)}), { color: ${q(r.options.material.color||'#ffffff')} });`);
      emitObjectKeys(r,id,animLines,stats,note);
    }
    else if(r.type==='mesh'){
      stats.meshes++;
      const parts=r.options?.parts||[];
      if(!parts.length){stats.skipped++;note(`"${r.name}" is an empty custom mesh and was skipped.`);continue;}
      const chain=[];
      parts.forEach((p,i)=>{
        const props=[];
        if(p.kind==='box'||p.kind==='voxel'||p.kind==='plane')props.push(`size: { x: ${r6(p.size?.[0]??1)}, y: ${r6(p.size?.[1]??1)}, z: ${r6(p.size?.[2]??1)} }`);
        else if(p.kind==='sphere')props.push(`radius: ${r6(p.radius??.5)}`);
        else if(p.kind==='cylinder'||p.kind==='cone')props.push(`radius: ${r6(p.radius??.5)}, height: ${r6(p.height??1)}`);
        else if(p.kind==='faces'){note(`"${r.name}" contains a custom faces part (freeform vertex geometry); scripts cannot express it, so the generated part is a placeholder box. Recreate it with the mesh editor if needed.`);props.push('size: { x: 1, y: 1, z: 1 }');}
        if(p.name)props.push(`name: ${q(p.name)}`);
        if(p.color!==undefined)props.push(`color: ${q(typeof p.color==='number'?'#'+p.color.toString(16).padStart(6,'0'):p.color)}`);
        if(p.opacity!==undefined&&p.opacity<1)props.push(`opacity: ${r6(p.opacity)}`);
        const edits=[p.position?`position: ${vec3(p.position)}`:'',p.rotation?`rotation: ${vec3(p.rotation,deg)}`:'',p.scale?`scale: ${vec3(p.scale)}`:''].filter(Boolean).join(', ');
        chain.push(`.${p.kind}({ ${props.join(', ')} })${edits?`.edit(${i}, { ${edits} })`:''}`);
      });
      objectLines.push(`  const ${id} = scene.addMesh(mesh.group(${q(id)})${chain.join('')}, { id: ${q(id)}, name: ${q(r.name||id)}, ${common}, ${rot}, ${scale} });`);
      emitObjectKeys(r,id,animLines,stats,note);
    }
    else{
      stats.skipped++;
      const kind=r.type==='tree'?'a decorative tree':r.type==='rock'?'a decorative rock':r.type==='lamp'?'a lamp prop':r.type==='import'?'an imported model':r.type==='voxel'?'a voxel-converted model':r.type==='image'?'an image object':'an unsupported object';
      note(`"${r.name}" is ${kind}; the scripting API cannot create it. It will not be rebuilt by this script.`);
    }
  }

  if(objectLines.length){
    L.push('  // ── Scene objects ────────────────────────────────────────────');
    L.push(...objectLines);
    L.push('');
  }
  if(animLines.length){
    L.push('  // ── Animation keys ───────────────────────────────────────────');
    // Grouped keys become ordinary editable keys; emit at most 120 per call is
    // handled by the compiler, so per-key calls stay readable.
    L.push(...animLines);
    L.push('');
  }

  // ── Camera ──
  if(cameraKeys.length){
    L.push('  // ── Camera travel ────────────────────────────────────────────');
    const sorted=cameraKeys.slice().sort((a,b)=>a.time-b.time);
    for(const k of sorted){
      let target=k.target;
      if(!target&&k.quaternion){
        // Derive a look target from a quaternion key (script keys are target-based).
        const qx=k.quaternion[0],qy=k.quaternion[1],qz=k.quaternion[2],qw=k.quaternion[3];
        const dx=-2*(qx*qz+qw*qy),dy=-2*(qy*qz-qw*qx),dz=-(1-2*(qx*qx+qy*qy));
        const p=k.position||[0,1,0];
        target=[p[0]+dx*4,p[1]+dy*4,p[2]+dz*4];
        note('A camera key stores a quaternion (it may include camera roll); scripts key the camera by target, so roll is not reproduced.');
      }
      const fields=[`time: ${r6(k.time)}`];
      if(k.position)fields.push(`position: ${vec3(k.position)}`);
      if(target)fields.push(`target: ${vec3(target)}`);
      if(k.fov!==undefined)fields.push(`fov: ${r6(k.fov)}`);
      const ease=k.ease&&SCRIPT_EASES.has(k.ease)?`, { ease: ${q(k.ease)} }`:'';
      L.push(`  timeline.keyCamera({ ${fields.join(', ')} }${ease});`);
      stats.cameraKeys++;
    }
    if(!cameraSmooth)note('The camera track uses linear (non-smooth) travel; scripts always use the editor\'s smooth spline. Toggle Smooth in the Camera inspector after running if needed.');
    L.push('');
  }

  // ── Lighting ──
  const light=snapshot.light||{};
  if(light.preset&&PRESET_TO_LIGHT[light.preset]){
    L.push(`  lights.setEnvironment({ preset: ${q(PRESET_TO_LIGHT[light.preset])}${light.exposure!==undefined?`, exposure: ${r6(light.exposure)}`:''}${light.fill!==undefined?`, ambient: ${r6(light.fill)}`:''}${light.fog!==undefined?`, fog: ${light.fog?'true':'false'}`:''}${light.fogColor?`, fogColor: ${q(light.fogColor)}`:''} });`);
    if(light.preset==='custom')0;
  }else{
    const env=[];
    if(light.exposure!==undefined)env.push(`exposure: ${r6(light.exposure)}`);
    if(light.fill!==undefined)env.push(`ambient: ${r6(light.fill)}`);
    if(light.fog!==undefined)env.push(`fog: ${light.fog?'true':'false'}`);
    if(light.fogColor)env.push(`fogColor: ${q(light.fogColor)}`);
    if(env.length)L.push(`  lights.setEnvironment({ ${env.join(', ')} });`);
    if(light.preset==='custom')note('The lighting setup is a custom preset; the script rebuilds the individual sun/environment values.');
  }
  if(light.az!==undefined||light.el!==undefined||light.power!==undefined){
    const sun=[];
    if(light.az!==undefined)sun.push(`azimuth: ${r6(light.az)}`);
    if(light.el!==undefined)sun.push(`elevation: ${r6(light.el)}`);
    if(light.power!==undefined)sun.push(`intensity: ${r6(light.power)}`);
    if(light.color)sun.push(`color: ${q(light.color)}`);
    if(light.soft!==undefined)sun.push(`softness: ${light.soft?'true':'false'}`);
    L.push(`  lights.setSun({ ${sun.join(', ')} });`);
    if(light.shadows!==undefined)note('Shadow enablement is an editor setting; scripts cannot toggle shadows.');
  }
  if(sunKeys.length){
    L.push('  // ── Sun animation ────────────────────────────────────────────');
    for(const k of sunKeys.slice().sort((a,b)=>a.time-b.time)){
      const fields=[`time: ${r6(k.time)}`];
      for(const f of ['azimuth','elevation','intensity','color'])if(k[f]!==undefined)fields.push(`${f}: ${typeof k[f]==='string'?q(k[f]):r6(k[f])}`);
      L.push(`  timeline.keySun({ ${fields.join(', ')} });`);
      stats.sunKeys++;
    }
    L.push('');
  }

  L.push('  timeline.setPlayhead(0);');
  L.push('}');
  // The scripting interpreter accepts at most 160 emitted commands; warn while
  // the script is still editable rather than failing validation unexpectedly.
  const commandEstimate=stats.terrainRuns+objectLines.length+animLines.length+cameraKeys.length+sunKeys.length+8;
  if(commandEstimate>150)note(`This scene needs about ${commandEstimate} script commands, close to or beyond the interpreter's 160-command budget. Validation may report "Too many script commands" — split the scene (for example, clear the terrain first, or remove some objects) and generate the remainder separately.`);
  if(snapshot.skyboxURL)note('A custom skybox image is set in the editor; scripts cannot set skyboxes.');
  if(snapshot.customTextures&&Object.keys(snapshot.customTextures).length)note('Custom block textures exist in this scene; scripts cannot assign custom textures.');
  if((snapshot.images||[]).length)note('Image objects exist in this scene; the scripting API cannot create them.');
  if(snapshot.audio&&snapshot.audio.source&&snapshot.audio.source!=='builtin'&&snapshot.audio.source!=='silent')note('The scene has an imported audio track; scripts cannot attach audio.');

  const code=L.join('\n')+'\n';
  const limitationList=[...limits];
  return {code,stats,limitations:limitationList};
}

function emitObjectKeys(r,id,animLines,stats,note){
  const keys=(r.keys||[]).slice().sort((a,b)=>a.time-b.time);
  for(const k of keys){
    const fields=[`time: ${r6(k.time)}`];
    if(k.position)fields.push(`position: ${vec3(k.position)}`);
    if(k.rotation)fields.push(`rotation: ${vec3(k.rotation,deg)}`);
    if(k.scale)fields.push(`scale: ${vec3(k.scale)}`);
    const ease=k.ease&&SCRIPT_EASES.has(k.ease)?`, { ease: ${q(k.ease)} }`:(k.ease?(()=>{note(`Key easing "${k.ease}" at ${k.time}s on "${r.name}" is timeline-only; the script uses smooth interpolation.`);return '';})():'');
    animLines.push(`  timeline.key(scene.get(${q(id)}), { ${fields.join(', ')} }${ease});`);
    stats.objectKeys++;
  }
  if(r.draft)note(`"${r.name}" has an unapplied pending edit; scripts reproduce saved keys only. Apply the pending edit first if you want it included.`);
  if(r.rotationMode==='spins')note(`"${r.name}" animates with full-spin rotation; script keys interpolate the shortest path. Set the object's rotation path to "Full spins" in the inspector after running.`);
  if(r.animPlaying!==undefined)note(`"${r.name}" plays an imported animation clip; clip playback state is not part of the scripting API.`);
}
